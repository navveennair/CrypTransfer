        run.font.name = 'Arial'
        run.font.size = Pt(14)
        run.font.bold = True
        
        doc.add_paragraph("\n")
        
        # Diagram
        p = doc.add_paragraph()
        run_d = p.add_run(diag_art)
        run_d.font.name = 'Courier New'
        run_d.font.size = Pt(8)
        
        doc.add_page_break()

